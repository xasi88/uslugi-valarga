const GROUPS = [
  ['iPhone и iPad', ['ios-safari', 'ios-other']],
  ['Android', ['android-chrome', 'android-yandex', 'android-samsung', 'android-edge', 'android-opera', 'android-firefox', 'android-other']],
  ['Компьютер', ['pc-edge', 'pc-chrome', 'pc-yandex', 'mac-safari', 'pc-firefox', 'pc-other']],
  ['WhatsApp, Telegram, Instagram', ['inapp']],
];

const COPY = '<button class="btn btn-line" type="button" data-act="copy-link">Скопировать адрес</button>';
function body(key) {
  const [, steps, note] = STEPS[key];
  return `<ol class="steps">${steps.map(s => `<li>${s}</li>`).join('')}</ol>`
    + (note ? `<p class="set-note">${note}</p>` : '') + (key === 'inapp' ? COPY : '');
}
const row = key => `<details class="vrow"><summary><span>${STEPS[key][0]}</span>${icon('down')}</summary>${body(key)}</details>`;

export function guideScreen() {
  const mine = browserOf(navigator.userAgent, navigator.maxTouchPoints);
  const now = installed()
    ? `<section class="set"><h2>${icon('ok')}Доска уже на экране</h2><p>Вы открыли доску со значка. Делать ничего не нужно.</p></section>`
    : canPrompt()
      ? `<section class="set g-now"><h2>${icon('app')}Установить одним касанием</h2>
        <p>Ваш браузер поставит значок сам. Нажмите кнопку и подтвердите.</p>
        <button class="btn btn-ink" type="button" data-act="install">Установить</button></section>` : '';
  const own = installed() ? '' : `<section class="set"><h2>${icon('app')}${canPrompt() ? 'Кнопка не сработала: ' : 'Ваш браузер: '}${STEPS[mine][0]}</h2>${body(mine)}</section>`;
  return `<div class="scr sets guide">
    <div class="set-head"><a class="back" href="#/" data-act="back" aria-label="Назад">${icon('arrow')}</a><h1>Как установить доску</h1></div>
    <p class="scr-lead">Доска встанет значком на экран, как приложение. Она откроется одним касанием, без поиска ссылки в переписке. Из магазина приложений ничего качать не нужно.</p>
    ${now}${own}
    <h2 class="g-head">Другой браузер или телефон</h2>
    ${GROUPS.map(([name, keys]) => [name, keys.filter(k => k !== mine)]).filter(([, keys]) => keys.length)
    .map(([name, keys]) => `<section class="set"><h2>${name}</h2><div class="ver-old">${keys.map(row).join('')}</div></section>`).join('')}
    ${adminLine('Не получается? Написать админу')}
  </div>`;
}
